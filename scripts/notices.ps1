# Writes THIRD-PARTY-NOTICES.md: the components shipped or downloaded beside Seekr, the npm
# packages in the panel, and every Rust crate in the build (cargo-about, with about.toml and
# about.hbs). Run after changing dependencies; check.ps1 fails if the file is out of date.
param([switch]$Check)

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$out = Join-Path $root 'THIRD-PARTY-NOTICES.md'

if (-not (Get-Command cargo-about -ErrorAction SilentlyContinue)) {
    cargo install cargo-about --version 0.9.2 --locked --features cli
    if ($LASTEXITCODE -ne 0) { throw 'cargo install cargo-about failed' }
}
# Into a file: cargo-about refuses PowerShell's pipe, which would re-encode its UTF-8.
$generated = Join-Path $env:TEMP "seekr-notices-$PID.md"
cargo about generate --manifest-path (Join-Path $root 'Cargo.toml') -c (Join-Path $root 'about.toml') -o $generated (Join-Path $root 'about.hbs') 2>$null
if ($LASTEXITCODE -ne 0) { throw 'cargo about failed' }
$rust = [IO.File]::ReadAllText($generated)
Remove-Item $generated

# The panel's runtime packages (not the build tools), with their own license files.
$wanted = (npm ls --omit=dev --all --parseable --prefix (Join-Path $root 'app') 2>$null) |
    Where-Object { $_ -match 'node_modules' } | ForEach-Object { (Resolve-Path $_).Path } | Sort-Object -Unique
$js = foreach ($path in $wanted) {
    $package = [IO.File]::ReadAllText((Join-Path $path 'package.json')) | ConvertFrom-Json
    $file = Get-ChildItem $path -File | Where-Object Name -match '^(LICEN[CS]E|COPYING)' | Select-Object -First 1
    $text = if ($file) { [IO.File]::ReadAllText($file.FullName).Trim() } else { "License: $($package.license) (no license file in the package)" }
    "### $($package.name) $($package.version) ($($package.license))`n`n``````n$text`n``````n"
}

