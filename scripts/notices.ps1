$text = ($header + "`n" + ($js -join "`n") + "`n" + ($rust -join "`n")).TrimEnd() + "`n"
$text = $text -replace "`r`n", "`n"
if ($Check) {
    $current = if (Test-Path $out) { [IO.File]::ReadAllText($out) -replace "`r`n", "`n" } else { '' }
    if ($current -ne $text) { Write-Host 'THIRD-PARTY-NOTICES.md is out of date: run scripts\notices.ps1'; exit 1 }
    Write-Host 'THIRD-PARTY-NOTICES.md is up to date'
    exit 0
}
